-- RedoxDB migration 002: every reported value of a molecule, with method and source.
-- Run once in the Supabase SQL editor after schema.sql.
create table if not exists public.measurements (
  id           bigint generated by default as identity primary key,
  molecule_id  bigint not null references public.molecules(id) on delete cascade,
  quantity     text not null check (quantity in ('e_ox', 'e_red', 'e00', 'e_star_ox', 'e_star_red')),
  value        numeric not null check (value between -5 and 5),
  value_type   text,                          -- E1/2, Ep, Ep/2, calc, E0,0, derived, reported
  kind         text not null default 'experimental' check (kind in ('experimental', 'computational')),
  method       text,                          -- e.g. 'CV, E_p/2 (100 mV/s, ...)' or 'DFT B3LYP/6-31+G(d,p), CPCM(MeCN)'
  solvent      text,
  electrolyte  text,
  ref_original text,
  conversion   text,
  doi          text check (doi is null or doi ~ '^10\.[0-9]{4,9}/\S+$'),
  source       text,
  confidence   text not null default 'medium' check (confidence in ('high', 'medium', 'low')),
  in_average   boolean not null default true,
  notes        text,
  status       text not null default 'approved' check (status in ('pending', 'approved', 'rejected')),
  import_key   text unique,
  submitted_by text,
  created_at   timestamptz not null default now()
);
create index if not exists measurements_molecule_idx on public.measurements (molecule_id);
alter table public.measurements enable row level security;
drop policy if exists meas_read on public.measurements;
drop policy if exists meas_submit on public.measurements;
drop policy if exists meas_curate on public.measurements;
drop policy if exists meas_delete on public.measurements;
create policy meas_read on public.measurements for select to authenticated
  using ((select public.is_curator()) or ((select public.is_member()) and status = 'approved'));
create policy meas_submit on public.measurements for insert to authenticated
  with check ((select public.is_curator()) or ((select public.is_member()) and status = 'pending' and submitted_by = (select public.my_email())));
create policy meas_curate on public.measurements for update to authenticated
  using ((select public.is_curator())) with check ((select public.is_curator()));
create policy meas_delete on public.measurements for delete to authenticated using ((select public.is_curator()));
drop trigger if exists measurements_audit on public.measurements;
create trigger measurements_audit after update or delete on public.measurements for each row execute function public.log_change();
revoke all on public.measurements from anon;
grant select, insert, update, delete on public.measurements to authenticated;
