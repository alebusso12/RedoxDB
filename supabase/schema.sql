-- RedoxDB — database schema for Supabase (Postgres). Run once in the SQL editor, then seed.sql.
-- Access model: NOTHING is readable without signing in. Every signed-in account must also be listed
-- in public.members with a role:
--   superadmin : everything, including adding/removing members and other superadmins
--   curator    : review queue, edit/approve/reject/delete entries
--   viewer     : read approved data, use the tools, submit entries for review
-- The superadmin is created once by hand (see README), never from this file.

create extension if not exists pgcrypto;

-- ---------------------------------------------------------------- members
create table if not exists public.members (
  email      text primary key check (email = lower(email) and email like '%@%'),
  role       text not null check (role in ('superadmin', 'curator', 'viewer')),
  note       text,
  added_by   text,
  added_at   timestamptz not null default now()
);
alter table public.members enable row level security;

-- Role of the signed-in user (null if not a member or e-mail not confirmed).
create or replace function public.my_role() returns text
language sql stable security definer set search_path = public, auth as $$
  select m.role from public.members m
  join auth.users u on lower(u.email) = m.email
  where u.id = auth.uid() and u.email_confirmed_at is not null
$$;
create or replace function public.my_email() returns text
language sql stable security definer set search_path = public, auth as $$
  select lower(u.email) from auth.users u where u.id = auth.uid()
$$;
create or replace function public.is_member() returns boolean language sql stable as $$ select public.my_role() is not null $$;
create or replace function public.is_curator() returns boolean language sql stable as $$ select coalesce(public.my_role() in ('superadmin', 'curator'), false) $$;
create or replace function public.is_superadmin() returns boolean language sql stable as $$ select coalesce(public.my_role() = 'superadmin', false) $$;
revoke all on function public.my_role(), public.my_email(), public.is_member(), public.is_curator(), public.is_superadmin() from public, anon;
grant execute on function public.my_role(), public.my_email(), public.is_member(), public.is_curator(), public.is_superadmin() to authenticated;

drop policy if exists members_read on public.members;
drop policy if exists members_write on public.members;
create policy members_read on public.members for select to authenticated
  using ((select public.is_superadmin()) or email = (select public.my_email()));
create policy members_write on public.members for all to authenticated
  using ((select public.is_superadmin())) with check ((select public.is_superadmin()));

-- Never leave the site without a superadmin.
create or replace function public.keep_one_superadmin() returns trigger language plpgsql as $$
begin
  if (tg_op = 'DELETE' and old.role = 'superadmin') or (tg_op = 'UPDATE' and old.role = 'superadmin' and new.role <> 'superadmin') then
    if (select count(*) from public.members where role = 'superadmin' and email <> old.email) = 0 then
      raise exception 'The last superadmin cannot be removed or demoted';
    end if;
  end if;
  return coalesce(new, old);
end $$;
drop trigger if exists members_keep_superadmin on public.members;
create trigger members_keep_superadmin before update or delete on public.members
  for each row execute function public.keep_one_superadmin();

-- ---------------------------------------------------------------- molecules
create table if not exists public.molecules (
  id               bigint generated by default as identity primary key,
  status           text not null default 'pending' check (status in ('pending', 'approved', 'rejected', 'merged')),
  name             text not null,
  iupac_name       text,
  aliases          text[] not null default '{}',
  smiles           text,
  cas              text,
  category         text not null check (category in ('photocatalyst', 'substrate')),
  kind             text check (kind in ('organic', 'organometallic', 'inorganic')),
  class            text,
  functional_groups text[] not null default '{}',
  e_ox             numeric check (e_ox between -4 and 4),
  e_ox_type        text check (e_ox_type in ('E1/2', 'Ep', 'Ep/2', 'calc')),
  e_red            numeric check (e_red between -4 and 4),
  e_red_type       text check (e_red_type in ('E1/2', 'Ep', 'Ep/2', 'calc')),
  e00              numeric check (e00 between 0.5 and 5),
  excited_state    text,
  e_star_ox        numeric check (e_star_ox between -4.5 and 4.5),
  e_star_red       numeric check (e_star_red between -4.5 and 4.5),
  tau_ns           numeric,
  lambda_abs_nm    numeric,
  lambda_em_nm     numeric,
  solvent          text,
  electrolyte      text,
  ref_original     text,
  conversion       text,
  doi              text check (doi is null or doi ~ '^10\.[0-9]{4,9}/\S+$'),
  review_doi       text check (review_doi is null or review_doi ~ '^10\.[0-9]{4,9}/\S+$'),
  confidence       text not null default 'medium' check (confidence in ('high', 'medium', 'low')),
  notes            text,
  curator_note     text,
  corrects_id      bigint references public.molecules(id) on delete cascade,
  import_key       text unique,
  submitted_by     text,
  reviewed_by      text,
  reviewed_at      timestamptz,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);
create index if not exists molecules_status_idx on public.molecules (status);
create index if not exists molecules_category_idx on public.molecules (category);
alter table public.molecules enable row level security;

drop policy if exists mol_read on public.molecules;
drop policy if exists mol_submit on public.molecules;
drop policy if exists mol_curate on public.molecules;
drop policy if exists mol_delete on public.molecules;
-- members read approved rows (and their own submissions); curators read everything
create policy mol_read on public.molecules for select to authenticated
  using ((select public.is_curator()) or ((select public.is_member()) and (status = 'approved' or submitted_by = (select public.my_email()))));
-- members may only add pending rows in their own name; curators may insert anything
create policy mol_submit on public.molecules for insert to authenticated
  with check ((select public.is_curator()) or ((select public.is_member()) and status = 'pending' and submitted_by = (select public.my_email()) and curator_note is null and reviewed_by is null));
create policy mol_curate on public.molecules for update to authenticated
  using ((select public.is_curator())) with check ((select public.is_curator()));
create policy mol_delete on public.molecules for delete to authenticated
  using ((select public.is_curator()));

create or replace function public.touch_molecule() returns trigger language plpgsql as $$
begin
  new.updated_at := now();
  if tg_op = 'UPDATE' and new.status is distinct from old.status then
    new.reviewed_by := public.my_email();
    new.reviewed_at := now();
  end if;
  return new;
end $$;
drop trigger if exists molecules_touch on public.molecules;
create trigger molecules_touch before update on public.molecules for each row execute function public.touch_molecule();

-- ---------------------------------------------------------------- reactions (advisor library)
create table if not exists public.reactions (
  id         text primary key,
  name       text not null,
  data       jsonb not null,
  status     text not null default 'approved' check (status in ('pending', 'approved', 'rejected')),
  updated_at timestamptz not null default now()
);
alter table public.reactions enable row level security;
drop policy if exists rx_read on public.reactions;
drop policy if exists rx_write on public.reactions;
create policy rx_read on public.reactions for select to authenticated
  using ((select public.is_curator()) or ((select public.is_member()) and status = 'approved'));
create policy rx_write on public.reactions for all to authenticated
  using ((select public.is_curator())) with check ((select public.is_curator()));

-- ---------------------------------------------------------------- audit log
create table if not exists public.audit (
  id      bigint generated always as identity primary key,
  at      timestamptz not null default now(),
  actor   text,
  tbl     text,
  row_id  text,
  action  text,
  before  jsonb,
  after   jsonb
);
alter table public.audit enable row level security;
drop policy if exists audit_read on public.audit;
create policy audit_read on public.audit for select to authenticated using ((select public.is_superadmin()));

create or replace function public.log_change() returns trigger language plpgsql security definer set search_path = public as $$
begin
  insert into public.audit (actor, tbl, row_id, action, before, after)
  values (public.my_email(), tg_table_name,
          coalesce((case when tg_op = 'DELETE' then to_jsonb(old) else to_jsonb(new) end)->>'id', (case when tg_op = 'DELETE' then to_jsonb(old) else to_jsonb(new) end)->>'email'),
          tg_op, case when tg_op <> 'INSERT' then to_jsonb(old) end, case when tg_op <> 'DELETE' then to_jsonb(new) end);
  return coalesce(new, old);
end $$;
drop trigger if exists molecules_audit on public.molecules;
create trigger molecules_audit after update or delete on public.molecules for each row execute function public.log_change();
drop trigger if exists members_audit on public.members;
create trigger members_audit after insert or update or delete on public.members for each row execute function public.log_change();

-- The anonymous role gets nothing at all.
revoke all on public.members, public.molecules, public.reactions, public.audit from anon;
grant select, insert, update, delete on public.members, public.molecules, public.reactions to authenticated;
grant select on public.audit to authenticated;
